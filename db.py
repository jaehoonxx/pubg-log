def get_map_info(map_name, category):
    """선택한 맵과 카테고리에 맞는 지도 이미지와 설명글을 가져옵니다."""
    conn = sqlite3.connect(DB_NAME)
    c = conn.cursor()

    c.execute("SELECT map_image, description FROM location_maps WHERE map_name = ? AND category = ?",
              (map_name, category))
    row = c.fetchone()
    conn.close()
    return row